#!/bin/sh
# ONLY for disposable containers: ordinary misconfigurations mirrored from real scan findings
# (permissions, setuid, permissive sshd, sudoers, secrets in files). Nothing here runs or hides code.
set -eu
host=$(hostname)
rpm_based=0
[ -f /etc/redhat-release ] && rpm_based=1

# --- SSH: permissive settings in drop-ins that are read before the main file (first value wins).
mkdir -p /etc/ssh/sshd_config.d
if [ "$rpm_based" = 1 ]; then
    printf '# Generated by Anaconda\nPermitRootLogin yes\n' > /etc/ssh/sshd_config.d/01-permitrootlogin.conf
fi
cat > /etc/ssh/sshd_config.d/00-lab-permissive.conf <<'SSH'
UsePAM no
PermitRootLogin yes
PasswordAuthentication yes
KbdInteractiveAuthentication no
PubkeyAuthentication yes
X11Forwarding yes
AllowTcpForwarding yes
AllowAgentForwarding yes
MaxAuthTries 10
LoginGraceTime 120
SSH

# --- Common permission/setuid faults (fixable by integrity/lse permission fixes).
chmod u+s /usr/bin/find                       # uncommon setuid binary
chmod 0666 /etc/crontab                       # group/other-writable system file
printf 'mysql -u root -pLabPassw0rd!\n' > /root/.bash_history
chmod 0644 /root/.bash_history                # credentials in shell history

# --- Cron job running a world-writable script (writable path referenced by cron).
printf '#!/bin/sh\n/bin/true\n' > /usr/local/bin/lab-backup.sh
chmod 0777 /usr/local/bin/lab-backup.sh
printf '*/5 * * * * root /usr/local/bin/lab-backup.sh\n' > /etc/cron.d/lab-backup
chmod 0666 /etc/cron.d/lab-backup

# --- Package file drift: wrong mode plus changed content. The mode is fixable; the content is not
# (package-content changes stay findings by design).
printf '\nCCDC-LAB-INTENTIONALLY-MODIFIED\n' >> /usr/bin/ssh
chmod 0777 /usr/bin/ssh

# --- Per-host stories, loosely following the real boxes.
case "$host" in
daffy)      # Debian blog
    chmod 0644 /etc/shadow ;;
elmer)      # Ubuntu 22.04 forums
    useradd --create-home --shell /bin/bash deploy
    passwd -l deploy >/dev/null
    printf 'deploy ALL=(ALL) NOPASSWD: ALL\n' > /etc/sudoers.d/90-deploy
    chmod 0440 /etc/sudoers.d/90-deploy
    chmod 0666 /etc/passwd ;;               # last: user tools reset this file's mode
foghorn)    # Rocky wiki/chat
    chmod u+s /usr/bin/cp
    printf '#!/bin/sh\ntar czf /var/lib/ccdc-lab/wiki-backup.tgz -C /var/lib/ccdc-lab .\n' > /usr/local/sbin/wiki-backup-root.sh
    chmod 0755 /usr/local/sbin/wiki-backup-root.sh
    printf '*/5 * * * * root /usr/local/sbin/wiki-backup-root.sh\n' > /etc/cron.d/wiki-backup ;;
sylvester)  # Rocky video streamer (aviary app)
    install -d -m 0777 /var/lib/birdcage
    printf 'BIRDCAGE_ADMIN_PASSWORD=Aviary-Default-1!\nBIRDCAGE_OPERATOR_PASSWORD=Aviary-Default-1!\nBIRDCAGE_CONTROL_TOKEN=lab-aviary-door-token\n' > /etc/birdcage.env
    chmod 0644 /etc/birdcage.env ;;        # secrets readable by everyone
marvin)     # Ubuntu 24.04 database
    printf '[client]\nuser=root\npassword=LabDbPassw0rd!\n' > /etc/ccdc-lab/db.cnf
    chmod 0644 /etc/ccdc-lab/db.cnf
    chmod u+s /usr/bin/env
    # A team-owned helper with no package: exists so "unowned" detection has an allow-list case.
    printf '#!/bin/sh\necho "vault unsealed (lab stand-in)"\n' > /usr/local/sbin/vault-auto-unseal
    chmod 0700 /usr/local/sbin/vault-auto-unseal
    printf '[Unit]\nDescription=Vault auto-unseal (lab stand-in)\n[Service]\nType=oneshot\nRemainAfterExit=yes\nExecStart=/usr/local/sbin/vault-auto-unseal\n[Install]\nWantedBy=multi-user.target\n' > /etc/systemd/system/vault-auto-unseal.service
    mkdir -p /etc/systemd/system/multi-user.target.wants
    ln -sf /etc/systemd/system/vault-auto-unseal.service /etc/systemd/system/multi-user.target.wants/ ;;
taz)        # Debian photo gallery
    chmod u+s /usr/bin/tar
    printf '%%sudo ALL=(ALL) NOPASSWD: ALL\n' > /etc/sudoers.d/90-sudo-nopasswd
    chmod 0440 /etc/sudoers.d/90-sudo-nopasswd ;;
esac
visudo -c >/dev/null
